"""Pydantic v2 schemas strictly matching docs/PRD.md contract specifications."""

from typing import Any, Literal, Optional
from pydantic import BaseModel, ConfigDict, Field, field_validator, model_serializer


class ChatRequest(BaseModel):
    """POST /chat request body."""

    session_id: str = Field(
        min_length=1,
        max_length=128,
        description="Required, 1-128 chars, generated by client. An unknown id starts a new session.",
    )
    message: str = Field(
        min_length=1,
        description="Required, 1-4000 chars after trimming whitespace.",
    )
    system_prompt: Optional[str] = Field(
        default=None,
        description="Optional; overrides the default system prompt for this session.",
    )

    @field_validator("session_id")
    @classmethod
    def validate_session_id(cls, v: str) -> str:
        stripped = v.strip()
        if len(stripped) < 1:
            raise ValueError("session_id cannot be empty or whitespace only")
        if len(stripped) > 128:
            raise ValueError("session_id cannot exceed 128 characters")
        return stripped

    @field_validator("message")
    @classmethod
    def validate_message(cls, v: str) -> str:
        stripped = v.strip()
        if len(stripped) < 1:
            raise ValueError("message cannot be empty or whitespace only")
        if len(stripped) > 4000:
            raise ValueError("message cannot exceed 4000 characters after trimming whitespace")
        return stripped


class ChatMetadata(BaseModel):
    """Metadata attached to each assistant message and /chat response."""

    resolution_source: Literal["LIVE_INFERENCE", "LLM_CACHE"] = Field(
        description="Exactly LIVE_INFERENCE or LLM_CACHE"
    )
    model: str = Field(
        description="LiteLLM model name that produced the reply"
    )
    latency_ms: int = Field(
        description="Server-measured time for this request, in milliseconds"
    )
    input_tokens: int = Field(
        description="Prompt tokens of this request (system + history + new message)"
    )
    output_tokens: int = Field(
        description="Completion tokens of this reply"
    )
    key_id: Optional[str] = Field(
        default=None,
        description="Id of the key that answered (key_1, key_2, ...). null on LLM_CACHE. Never the key itself.",
    )
    fallback_attempts: int = Field(
        description="Keys that failed before this one succeeded. 0 on LLM_CACHE."
    )

    model_config = ConfigDict(extra="allow")


class ChatResponse(BaseModel):
    """POST /chat 200 response."""

    session_id: str = Field(description="Echo of the request value")
    reply: str = Field(description="Assistant text, non-empty")
    metadata: ChatMetadata = Field(description="Per-request execution metadata")

    model_config = ConfigDict(extra="allow")


class MessageItem(BaseModel):
    """Single item in session history."""

    role: Literal["user", "assistant"] = Field(description="Role: user or assistant")
    content: str = Field(description="Message text")
    metadata: Optional[dict[str, Any]] = Field(
        default=None,
        description="Metadata dictionary, present on assistant messages only",
    )

    @model_serializer(mode="wrap")
    def serialize_model(self, handler):
        dump = handler(self)
        if dump.get("metadata") is None:
            dump.pop("metadata", None)
        return dump

    model_config = ConfigDict(extra="allow")


class SessionHistoryResponse(BaseModel):
    """GET /sessions/{session_id}/messages 200 response."""

    session_id: str = Field(description="Session ID")
    messages: list[MessageItem] = Field(
        description="Stored history of one session from SQLite, oldest first, without the system prompt"
    )

    model_config = ConfigDict(extra="allow")


class HealthResponse(BaseModel):
    """GET /health 200 response."""

    status: str = Field(default="ok", description="Status string: ok")
    keys_configured: int = Field(description="Number of provider keys loaded")
    cache_enabled: bool = Field(default=True, description="Whether LiteLLM caching is active")

    model_config = ConfigDict(extra="allow")


class ErrorResponse(BaseModel):
    """Standard error response shape."""

    detail: Any = Field(description="Error detail message or validation errors")
